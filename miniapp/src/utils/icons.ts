/** 去掉变体选择符 / 肤色 / ZWJ 组合，只留首个基础码点 */
function baseGlyph(s: string): string {
  const cp = [...s].filter((c) => {
    const n = c.codePointAt(0) ?? 0
    return n !== 0xfe0f && n !== 0x200d && !(n >= 0x1f3fb && n <= 0x1f3ff)
  })
  return cp[0] ?? ''
}

const EMOJI_ICON_MAP: Record<string, IconName> = {}
for (const [glyph, icon] of EMOJI_ICON_ENTRIES) EMOJI_ICON_MAP[baseGlyph(glyph)] = icon

/** 查不到时返回 undefined，由调用方决定兜底 */
export function iconForEmoji(emoji?: string): IconName | undefined {
  if (!emoji) return undefined
  return EMOJI_ICON_MAP[baseGlyph(emoji)]
}

